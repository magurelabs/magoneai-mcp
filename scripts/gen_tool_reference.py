"""Generate `docs/TOOLS.md`, the reference for all 233 tools, from the code.

A catalogue of 20 connectors and 233 tools is unusable without a list, and a
hand-written list of 233 anything is wrong within a week. Everything here is
read from the decorators, and `--check` regenerates and diffs on every pull
request, so the document cannot quietly stop describing the code.

This repository has now produced the same defect three times in three places:
module docstrings claiming tool counts that had drifted, a TODO inventory
that claimed to be generated and was not, and provenance comments saying
tools were unreviewed after they had been. Each was a true sentence that
became false because something else changed correctly. A generator plus a
diff is the only form of documentation that survives that.

What each tool's row carries and why:

- **read-only** is the flag `MCP_READ_ONLY` keys on, so it is what decides
  whether a deployment built to refuse writes will offer the tool at all.
- **destructive** warns a client that the tool overwrites or removes rather
  than only adding. Per the spec it defaults to true for any tool that is not
  read-only, so `false` is a claim, not an absence.
- **credentials** is how many request headers the tool may receive. A tool
  needing credentials with zero declared calls its vendor with nothing.

    python scripts/gen_tool_reference.py
    python scripts/gen_tool_reference.py --check
"""

import argparse
import ast
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CONNECTORS = REPO_ROOT / "connectors"
PUBLICATION = CONNECTORS / "publication.json"
REFERENCE = REPO_ROOT / "docs" / "TOOLS.md"


def tools_in(server: Path) -> list[dict]:
    source = server.read_text(encoding="utf-8")
    found: list[dict] = []
    for node in ast.walk(ast.parse(source)):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for dec in node.decorator_list:
            if not (isinstance(dec, ast.Call) and getattr(dec.func, "attr", "") == "tool"):
                continue
            entry = {
                "name": node.name,
                "description": "",
                "read_only": False,
                "destructive": False,
                "credentials": 0,
            }
            for kw in dec.keywords:
                if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                    entry["name"] = kw.value.value
                elif kw.arg == "description" and isinstance(kw.value, ast.Constant):
                    entry["description"] = kw.value.value
                elif kw.arg == "annotations" and isinstance(kw.value, ast.Call):
                    for flag in kw.value.keywords:
                        value = getattr(flag.value, "value", None)
                        if flag.arg == "readOnlyHint":
                            entry["read_only"] = value is True
                        elif flag.arg == "destructiveHint":
                            entry["destructive"] = value is True
                elif kw.arg == "credential_headers" and isinstance(kw.value, (ast.List, ast.Tuple)):
                    entry["credentials"] = len(kw.value.elts)
            found.append(entry)
    return sorted(found, key=lambda t: t["name"])


def first_sentence(text: str, limit: int = 150) -> str:
    """One sentence, table-safe.

    Descriptions here run to several hundred characters because they are
    written for a model choosing a tool, not for a person scanning a table.
    """
    flat = " ".join(text.split())
    for end in (". ", "? ", "! "):
        if end in flat[:limit]:
            flat = flat[: flat.index(end) + 1]
            break
    if len(flat) > limit:
        flat = flat[: limit - 1].rstrip() + "…"
    return flat.replace("|", "\\|")


def build() -> str:
    statuses = json.loads(PUBLICATION.read_text(encoding="utf-8"))["connectors"]
    packages = sorted(p for p in CONNECTORS.iterdir() if (p / "server.py").exists())

    catalogue = {p.name: tools_in(p / "server.py") for p in packages}
    total = sum(len(v) for v in catalogue.values())
    read_only = sum(1 for v in catalogue.values() for t in v if t["read_only"])
    destructive = sum(1 for v in catalogue.values() for t in v if t["destructive"])

    out = [
        "# Tool reference",
        "",
        "Generated by `scripts/gen_tool_reference.py` from the decorators "
        "themselves. Do not edit: `--check` regenerates and diffs on every "
        "pull request, so an edit here is reverted by CI rather than kept.",
        "",
        f"**{total} tools across {len(packages)} connectors.** {read_only} are read-only "
        f"and {destructive} are marked destructive.",
        "",
        "`MCP_READ_ONLY=1` offers only the read-only ones and refuses the rest "
        "on call. `destructive` means the tool overwrites or removes rather "
        "than only adding; the specification makes that the default for any "
        "tool that is not read-only, so a `no` in that column is a claim "
        "somebody made and not merely an absence.",
        "",
    ]

    for package in packages:
        entries = catalogue[package.name]
        status = statuses.get(package.name, {})
        label = "publishable" if status.get("status") == "ready" else "not published"
        reason = status.get("reason", "")

        out.append(f"## `{package.name}`")
        out.append("")
        out.append(
            f"{len(entries)} tools, {sum(1 for t in entries if t['read_only'])} read-only. "
            f"**{label}.**"
        )
        if label == "not published" and reason:
            out.append("")
            out.append(f"> {first_sentence(reason, 400)}")
        out.append("")
        out.append("| tool | read-only | destructive | credentials | description |")
        out.append("|---|---|---|---|---|")
        for tool in entries:
            out.append(
                f"| `{tool['name']}` "
                f"| {'yes' if tool['read_only'] else 'no'} "
                f"| {'yes' if tool['destructive'] else 'no'} "
                f"| {tool['credentials']} "
                f"| {first_sentence(tool['description'])} |"
            )
        out.append("")

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the reference has drifted")
    args = parser.parse_args()

    expected = build()
    if args.check:
        if not REFERENCE.exists():
            print(f"{REFERENCE.relative_to(REPO_ROOT)} does not exist")
            print("Run: python scripts/gen_tool_reference.py")
            return 1
        if REFERENCE.read_text(encoding="utf-8") != expected:
            print(f"{REFERENCE.relative_to(REPO_ROOT)} no longer matches the code")
            print("Run: python scripts/gen_tool_reference.py")
            return 1
        print("tool reference: matches the code")
        return 0

    REFERENCE.parent.mkdir(parents=True, exist_ok=True)
    changed = not REFERENCE.exists() or REFERENCE.read_text(encoding="utf-8") != expected
    REFERENCE.write_text(expected, encoding="utf-8")
    print("tool reference regenerated" if changed else "tool reference already current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
